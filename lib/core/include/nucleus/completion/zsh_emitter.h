#ifndef HPP_GUARD_NUCLEUS_COMPLETION_ZSH_EMITTER_H
#define HPP_GUARD_NUCLEUS_COMPLETION_ZSH_EMITTER_H

#include "nucleus/completion/zsh_spec.h"
#include "nucleus/completion/zsh_ordinal.h"
#include "nucleus/completion/shell_emitter.h"
#include "nucleus/completion/zsh_safe_ascii.h"
#include "nucleus/completion/completion_model.h"

#include "nucleus/utility/escaped_text.h"

#include <string>
#include <algorithm>

namespace nucleus {

// The zsh emitter. zsh has its OWN completion grammar -- it is deliberately not a
// re-quoted bash script. The output is a `#compdef`-tagged function that calls
// `_arguments -s`, one spec per flag:
//
//     '--logging-level=[set the logging level]:level:(debug info warn error)'
//
// zsh parses `--flag=` natively and drives the value menu from the `(...)` group,
// so there is no COMP_WORDBREAKS handling here at all -- that whole class of bash
// edge case simply does not exist in this dialect. The flags WITHOUT a value set
// emit a bare `'--flag[desc]'` spec. The spec grammar and its quoting live in
// zsh_spec.h, a description is rendered by zsh_description.h, and for a model with an
// ordinal option the specs zsh_ordinal.h builds from the typed word precede the static ones.
// Autoloaded from $fpath as `_nucleus_<ident>` the file body completes, and sourced after compinit it registers.
class zsh_emitter final : public shell_emitter
{
public:
    std::string emit(const completion_model &model) const override
    {
        const std::string fn  = function_name(model.prog);
        std::string       out = header(model.prog);
        if(guarded(model))
            out += "autoload -Uz is-at-least\n";
        if(has_ordinal_options(model))
            out += detail::zsh_ordinal_function(fn);
        out += fn + "()\n{\n" + guarded_block(fn, model) + arguments_line(model);
        return out + "}\n" + tail(fn, model.prog);
    }

private:
    static std::string header(const std::string &prog)
    {
        const std::string shown = escaped_text(prog);
        std::string       out   = "#compdef " + shown + "\n";
        out += "# zsh completion for " + shown + "\n";
        return out + "# Generated by nucleus -- do not edit by hand.\n";
    }

    // Only an autoload runs this text as the function itself, in the `loadautofunc` evaluation context.
    // The funcstack test turns away an `eval` of the text, whose context is `eval`, and the context test turns
    // away a file sourced under the function's own name, which funcstack reports as that name.
    static std::string tail(const std::string &fn, const std::string &prog)
    {
        const std::string test = R"(if [ "$funcstack[1]" = ")" + fn + R"(" ] && [ "${zsh_eval_context[-1]}" != file ]; then )";
        return test + fn + R"( "$@"; else compdef )" + fn + " " + detail::zsh_word(prog) + "; fi\n";
    }

    static bool guarded_spec(const completion_option &option) { return detail::zsh_flag_outside_safe_ascii(option.flag); }

    static bool guarded(const completion_model &model) { return std::ranges::any_of(model.options, guarded_spec); }

    static std::string guarded_block(const std::string &fn, const completion_model &model)
    {
        if(!guarded(model))
            return "";
        std::string out = "    local -a quoted_specs\n    local -i inserts_quoted=0\n    is-at-least 5.9 && inserts_quoted=1\n";
        if(has_ordinal_options(model))
            out += std::string(detail::zsh_ordinal_locals) + detail::zsh_ordinal_calls(fn, model, false);
        out += "    if (( inserts_quoted )); then\n" + detail::zsh_ordinal_calls(fn, model, true) + "        quoted_specs=(\n";
        for(const completion_option &option : model.options)
        {
            if(guarded_spec(option))
                out += "            " + detail::zsh_single_quote(detail::zsh_spec(option)) + "\n";
        }
        return out + "        )\n    fi\n";
    }

    static std::string arguments_line(const completion_model &model)
    {
        const std::string ordinal = has_ordinal_options(model) ? " \"${ordinal_specs[@]}\"" : "";
        const std::string specs   = spec_lines(model);
        return "    _arguments -s" + ordinal + (specs.empty() ? "\n" : " \\\n" + specs);
    }

    // zsh inserts a word matching several specs differently by their order; the guarded specs follow the others so a
    // wildcard flag still follows its plain sibling.
    static std::string spec_lines(const completion_model &model)
    {
        std::string out;
        for(const completion_option &option : model.options)
        {
            if(!guarded_spec(option))
                out += (out.empty() ? "        " : " \\\n        ") + detail::zsh_single_quote(detail::zsh_spec(option));
        }
        if(guarded(model))
            out += (out.empty() ? "        " : " \\\n        ") + std::string("\"${quoted_specs[@]}\"");
        return out.empty() ? out : out + "\n";
    }

    static std::string function_name(const std::string &prog) { return "_nucleus_" + sanitize_ident(prog); }

    static std::string sanitize_ident(const std::string &text)
    {
        std::string out;
        out.reserve(text.size());
        for(char const c : text)
        {
            const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
                         || (c >= '0' && c <= '9') || c == '_';
            out.push_back(ok ? c : '_');
        }
        return out;
    }
};

}

#endif
