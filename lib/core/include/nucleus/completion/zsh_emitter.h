#ifndef HPP_GUARD_NUCLEUS_COMPLETION_ZSH_EMITTER_H
#define HPP_GUARD_NUCLEUS_COMPLETION_ZSH_EMITTER_H

#include "nucleus/completion/zsh_spec.h"
#include "nucleus/completion/zsh_ordinal.h"
#include "nucleus/completion/shell_emitter.h"
#include "nucleus/completion/completion_model.h"

#include "nucleus/utility/escaped_text.h"

#include <string>
#include <cstddef>

namespace nucleus {

// The zsh emitter. zsh has its OWN completion grammar -- it is deliberately not a
// re-quoted bash script. The output is a `#compdef`-tagged function that calls
// `_arguments -s`, one spec per flag:
//
//     '--logging-level=[set the logging level]:level:(debug info warn error)'
//
// zsh parses `--flag=` natively and drives the value menu from the `(...)` group,
// so there is no COMP_WORDBREAKS handling here at all -- that whole class of bash
// edge case simply does not exist in this dialect. The flags WITHOUT a value set
// emit a bare `'--flag[desc]'` spec. The spec grammar and its quoting live in
// zsh_spec.h, a description is rendered by zsh_description.h, and for a model with an
// ordinal option the specs zsh_ordinal.h builds from the typed word precede the static ones.
class zsh_emitter final : public shell_emitter
{
public:
    std::string emit(const completion_model &model) const override
    {
        const std::string ident = sanitize_ident(model.prog);
        std::string       out   = header(model.prog);
        if(has_ordinal_options(model))
            out += detail::zsh_ordinal_function(ident);
        out += function_head(ident, model) + spec_lines(model);
        return out + "}\n_" + ident + " \"$@\"\n";
    }

private:
    static std::string header(const std::string &prog)
    {
        const std::string shown = escaped_text(prog);
        std::string       out   = "#compdef " + shown + "\n";
        out += "# zsh completion for " + shown + "\n";
        return out + "# Generated by nucleus -- do not edit by hand.\n";
    }

    static std::string function_head(const std::string &ident, const completion_model &model)
    {
        const std::string head = "_" + ident + "()\n{\n";
        if(!has_ordinal_options(model))
            return head + "    _arguments -s \\\n";
        return head + detail::zsh_ordinal_calls(ident, model) + "    _arguments -s \"${ordinal_specs[@]}\" \\\n";
    }

    static std::string spec_lines(const completion_model &model)
    {
        std::string out;
        for(std::size_t i = 0; i < model.options.size(); ++i)
        {
            const bool last = (i + 1 == model.options.size());
            out += "        " + detail::zsh_single_quote(detail::zsh_spec(model.options[i]));
            out += last ? "\n" : " \\\n";
        }
        return out;
    }

    static std::string sanitize_ident(const std::string &text)
    {
        std::string out;
        out.reserve(text.size());
        for(char const c : text)
        {
            const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
                         || (c >= '0' && c <= '9') || c == '_';
            out.push_back(ok ? c : '_');
        }
        return out;
    }
};

}

#endif
