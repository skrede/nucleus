#ifndef HPP_GUARD_NUCLEUS_COMPLETION_BASH_EMITTER_H
#define HPP_GUARD_NUCLEUS_COMPLETION_BASH_EMITTER_H

#include "nucleus/completion/bash_ordinal.h"
#include "nucleus/completion/bash_quoting.h"
#include "nucleus/completion/shell_emitter.h"
#include "nucleus/completion/bash_line_form.h"
#include "nucleus/completion/completion_model.h"

#include "nucleus/utility/escaped_text.h"

#include <string>
#include <string_view>

namespace nucleus {

// readline inserts a reply under the quote open at the cursor and keeps the text typed before that quote, so a reply is
// spelled for the quote the typed word leaves open and nothing is offered for a word ending inside a quote it reopened.
// bash splits `=` and every other unquoted COMP_WORDBREAKS byte into a word of its own, so a value is completed from
// the word after `=` alone and never past another break byte.
class bash_emitter final : public shell_emitter
{
public:
    std::string emit(const completion_model &model) const override
    {
        const std::string ident  = sanitize_ident(model.prog);
        const std::string prefix = "_" + ident;
        std::string       out    = "# bash completion for " + escaped_text(model.prog) + "\n";
        out += "# Generated by nucleus -- do not edit by hand.\n" + detail::bash_line_lookup(ident, model);
        if(has_ordinal_options(model))
            out += detail::bash_ordinal_functions(ident, model);
        out += opening(ident, model) + value_section(ident, model, prefix) + flag_section(ident, model, prefix);
        out += std::string(registration_gate) + "complete -F _" + ident + "_complete ";
        out += detail::bash_line_word(model.prog) + "; fi\n";
        return out;
    }

private:
    // The completion is registered only on bash 5.0 or later, the floor the replies are built for, so an older
    // bash completes nothing. The check guards the registration rather than returning early, which holds whether
    // the script is sourced, eval'd or executed, and bash reaches it only if everything above it also parses on
    // bash 3.2.
    static constexpr std::string_view registration_gate = R"(if [ "${BASH_VERSINFO[0]}" -ge 5 ]; then )";

    static std::string opening(const std::string &ident, const completion_model &model)
    {
        std::string out = "_" + ident + "_complete()\n{\n";
        out += "    local -\n";
        out += "    local cur prev words cword\n";
        out += "    COMPREPLY=()\n";
        out += "    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n";
        out += "    local flags=" + detail::bash_single_quote(detail::bash_join_flags(model.options)) + "\n";
        if(has_ordinal_options(model))
            out += "    local ordinal_name\n";
        return out + "\n";
    }

    static std::string value_section(const std::string &ident, const completion_model &model, const std::string &prefix)
    {
        std::string out = "    local whole=\"$cur\"\n";
        out += "    if [[ \"${COMP_WORDS[COMP_CWORD-1]}\" == \"=\" ]]; then\n";
        out += "        whole=\"${COMP_WORDS[COMP_CWORD-2]}=${cur}\"\n";
        out += "    elif [[ \"$cur\" == \"=\" ]]; then\n";
        out += "        whole=\"${COMP_WORDS[COMP_CWORD-1]}=\"\n";
        out += "    fi\n";
        out += "    if [[ \"$whole\" == --*=* ]]; then\n";
        out += "        local cur=\"$whole\"\n";
        out += "        local flag=\"${cur%%=*}\"\n";
        out += "        local val=\"${cur#*=}\"\n";
        out += "        case \"$flag\" in\n";
        out += value_arms(model, prefix);
        out += "        esac\n";
        out += detail::bash_ordinal_dispatch(ident, model, prefix);
        out += "        return 0\n";
        return out + "    fi\n\n";
    }

    static std::string value_arms(const completion_model &model, const std::string &prefix)
    {
        std::string out;
        for(const completion_option &opt : model.options)
        {
            if(opt.values.empty() || has_ordinal_slots(opt))
                continue;
            out += "        " + detail::bash_single_quote(detail::bash_line_word(opt.flag)) + ")\n";
            out += detail::bash_value_reply("            ", opt, prefix);
            out += "            ;;\n";
        }
        return out;
    }

    static std::string flag_section(const std::string &ident, const completion_model &model, const std::string &prefix)
    {
        const std::string also = has_ordinal_options(model) ? "_" + ident + "_ordinals \"$cur\"" : "";
        std::string       out  = detail::bash_reply_assignment("    ", "\"$flags\"", "$cur", prefix, also);
        out += "    __ltrim_colon_completions \"$cur\" 2>/dev/null\n";
        return out + "    return 0\n}\n";
    }

    // A safe shell identifier for the function name (non-alnum -> '_').
    static std::string sanitize_ident(const std::string &text)
    {
        std::string out;
        out.reserve(text.size());
        for(char const c : text)
        {
            const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
                         || (c >= '0' && c <= '9') || c == '_';
            out.push_back(ok ? c : '_');
        }
        return out;
    }
};

}

#endif
