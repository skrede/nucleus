#ifndef HPP_GUARD_NUCLEUS_COMPLETION_BASH_EMITTER_H
#define HPP_GUARD_NUCLEUS_COMPLETION_BASH_EMITTER_H

#include "nucleus/completion/bash_ordinal.h"
#include "nucleus/completion/bash_quoting.h"
#include "nucleus/completion/bash_line_form.h"
#include "nucleus/completion/shell_emitter.h"
#include "nucleus/completion/completion_model.h"

#include "nucleus/utility/escaped_text.h"

#include <string>

namespace nucleus {

// The bash emitter. It renders a `complete -F` function bound to the program. All
// of bash's sharp edges are confined to it and to bash_quoting.h, bash_line_form.h and bash_ordinal.h:
//
//   * COMP_WORDBREAKS. bash 4 and later split `=` into a word of its own and 3.2 does not, so
//     the value branch rebuilds `--flag=value` from the word before `=`, or from the previous
//     word when `=` is itself the current word, then completes only the value tail.
//   * `:` breaks words too. bash 3.2 keeps the value one word, and each value reply drops the
//     typed text through its last colon, which readline leaves on the line; bash 4 and later
//     split the value at the colon and nothing re-joins it, so they offer no value past one.
//     With `:` absent from COMP_WORDBREAKS neither version splits and nothing is dropped.
//
// None of this leaks back into the generator or the model.
class bash_emitter final : public shell_emitter
{
public:
    std::string emit(const completion_model &model) const override
    {
        const std::string ident  = sanitize_ident(model.prog);
        const std::string lookup = detail::bash_line_lookup(ident, model);
        const std::string line   = lookup.empty() ? std::string() : "_" + ident + "_line";
        std::string       out    = "# bash completion for " + escaped_text(model.prog) + "\n";
        out += "# Generated by nucleus -- do not edit by hand.\n" + lookup;
        if(has_ordinal_options(model))
            out += detail::bash_ordinal_functions(ident, model);
        out += opening(ident, model) + value_section(ident, model, line) + flag_section(ident, model, line);
        out += "complete -F _" + ident + "_complete " + detail::bash_line_word(model.prog) + "\n";
        return out;
    }

private:
    static std::string opening(const std::string &ident, const completion_model &model)
    {
        std::string out = "_" + ident + "_complete()\n{\n";
        out += "    local cur prev words cword\n";
        out += "    COMPREPLY=()\n";
        out += "    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n";
        out += "    local flags=" + detail::bash_single_quote(detail::bash_join_flags(model.options)) + "\n";
        if(has_ordinal_options(model))
            out += "    local ordinal_name\n";
        return out + "\n";
    }

    static std::string value_section(const std::string &ident, const completion_model &model, const std::string &line)
    {
        std::string out = "    local whole=\"$cur\"\n";
        out += "    if [[ \"${COMP_WORDS[COMP_CWORD-1]}\" == \"=\" ]]; then\n";
        out += "        whole=\"${COMP_WORDS[COMP_CWORD-2]}=${cur}\"\n";
        out += "    elif [[ \"$cur\" == \"=\" ]]; then\n";
        out += "        whole=\"${COMP_WORDS[COMP_CWORD-1]}=\"\n";
        out += "    fi\n";
        out += "    if [[ \"$whole\" == --*=* ]]; then\n";
        out += "        local cur=\"$whole\"\n";
        out += "        local flag=\"${cur%%=*}\"\n";
        out += "        local val=\"${cur#*=}\"\n";
        out += "        case \"$flag\" in\n";
        out += value_arms(model, line);
        out += "        esac\n";
        out += detail::bash_ordinal_dispatch(ident, model, line);
        out += "        return 0\n";
        return out + "    fi\n\n";
    }

    static std::string value_arms(const completion_model &model, const std::string &line)
    {
        std::string out;
        for(const completion_option &opt : model.options)
        {
            if(opt.values.empty() || has_ordinal_slots(opt))
                continue;
            out += "        " + detail::bash_single_quote(detail::bash_line_word(opt.flag)) + ")\n";
            out += detail::bash_value_reply("            ", opt, line);
            out += "            ;;\n";
        }
        return out;
    }

    static std::string flag_section(const std::string &ident, const completion_model &model, const std::string &line)
    {
        const std::string also = has_ordinal_options(model) ? "_" + ident + "_ordinals \"$cur\"" : "";
        std::string       out  = detail::bash_reply_assignment("    ", "\"$flags\"", "$cur", line, also);
        out += "    __ltrim_colon_completions \"$cur\" 2>/dev/null\n";
        return out + "    return 0\n}\n";
    }

    // A safe shell identifier for the function name (non-alnum -> '_').
    static std::string sanitize_ident(const std::string &text)
    {
        std::string out;
        out.reserve(text.size());
        for(char const c : text)
        {
            const bool ok = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')
                         || (c >= '0' && c <= '9') || c == '_';
            out.push_back(ok ? c : '_');
        }
        return out;
    }
};

}

#endif
